    // MARK: - 高性能射线交叉法点在多边形内判定 (Jordan Curve PIP)
    private static func isPointInPolygon(lon: Double, lat: Double, polygon: [(Double, Double)]) -> Bool {
        var inside = false
        let count = polygon.count
        var j = count - 1
        for i in 0..<count {
            let (xi, yi) = polygon[i]
            let (xj, yj) = polygon[j]
            if ((yi > lat) != (yj > lat)) && (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
                inside.toggle()
            }
            j = i
        }
        return inside
    }

    // MARK: 判断坐标是否在中国大陆境内 (严格排除港澳台、日韩、东南亚及欧美等所有境外区域)
    static func isInChina(lat: Double, lon: Double) -> Bool {
        // 1. 纳秒级外包粗筛：纬度不在 18.0...53.6 或经度不在 73.4...135.1 直接判定为境外
        if lat < 18.0 || lat > 53.6 || lon < 73.4 || lon > 135.1 {
            return false
        }

        // 2. 港澳台专属多边形精准剔除（保证香港维港/中环、澳门大三巴、台北101等0漂移）
        if lat >= 22.14 && lat <= 22.58 && lon >= 113.82 && lon <= 114.45 {
            for ring in hkPolygons {
                if isPointInPolygon(lon: lon, lat: lat, polygon: ring) {
                    return false
                }
            }
        }
        if lat >= 22.10 && lat <= 22.25 && lon >= 113.50 && lon <= 113.62 {
            for ring in macauPolygons {
                if isPointInPolygon(lon: lon, lat: lat, polygon: ring) {
                    return false
                }
            }
        }
        if lat >= 21.80 && lat <= 25.50 && lon >= 119.80 && lon <= 122.20 {
            for ring in taiwanPolygons {
                if isPointInPolygon(lon: lon, lat: lat, polygon: ring) {
                    return false
                }
            }
        }

        // 3. 邻国半岛与岛屿极速排除（韩国、日本本土/冲绳等）
        if lat <= 38.6 && lon >= 126.0 { // 韩国半岛
            return false
        }
        if lon >= 128.0 && lat >= 30.0 { // 日本九州及本土
            return false
        }
        if lon >= 122.9 && lat >= 24.0 && lat <= 28.5 { // 日本冲绳及琉球群岛
            return false
        }

        // 4. 珠海拱北/横琴陆地微缓冲保障（防止简化多边形边缘剪裁）
        if lat >= 22.18 && lat <= 22.26 && lon >= 113.50 && lon <= 113.58 {
            return true
        }

        // 5. 中国大陆及主要岛屿多边形精准命中判定
        if isPointInPolygon(lon: lon, lat: lat, polygon: mainlandPolygon) {
            return true
        }
        if isPointInPolygon(lon: lon, lat: lat, polygon: hainanPolygon) {
            return true
        }
        if isPointInPolygon(lon: lon, lat: lat, polygon: zhoushanPolygon) {
            return true
        }
        if isPointInPolygon(lon: lon, lat: lat, polygon: xiamenPolygon) {
            return true
        }

        return false
    }

    static func isInChina(_ coord: CLLocationCoordinate2D) -> Bool {
        return isInChina(lat: coord.latitude, lon: coord.longitude)
    }

    // MARK: WGS-84 -> GCJ-02 (加偏)
    static func wgs84ToGcj02(lat: Double, lon: Double, force: Bool = false) -> (lat: Double, lon: Double) {
        guard force || isInChina(lat: lat, lon: lon) else {
            return (lat, lon)
        }

        var dLat = transformLat(x: lon - 105.0, y: lat - 35.0)
        var dLon = transformLon(x: lon - 105.0, y: lat - 35.0)
        let radLat = lat / 180.0 * .pi
        var magic = sin(radLat)
        magic = 1.0 - ee * magic * magic
        let sqrtMagic = sqrt(magic)

        dLat = (dLat * 180.0) / ((a * (1.0 - ee)) / (magic * sqrtMagic) * .pi)
        dLon = (dLon * 180.0) / (a / sqrtMagic * cos(radLat) * .pi)

        return (lat + dLat, lon + dLon)
    }

    static func wgs84ToGcj02(_ coord: CLLocationCoordinate2D, force: Bool = false) -> CLLocationCoordinate2D {
        let (lat, lon) = wgs84ToGcj02(lat: coord.latitude, lon: coord.longitude, force: force)
        return CLLocationCoordinate2D(latitude: lat, longitude: lon)
    }

    // MARK: GCJ-02 -> WGS-84 (精确多阶迭代反解纠偏，误差 < 0.02米)
    static func gcj02ToWgs84(lat: Double, lon: Double, force: Bool = false) -> (lat: Double, lon: Double) {
        guard force || isInChina(lat: lat, lon: lon) else {
            return (lat, lon)
        }

        var wgsLat = lat
        var wgsLon = lon

        // 采用 4 轮迭代梯度收敛反解，精度达 0.0000001 度级别
        for _ in 0..<4 {
            let (testGcjLat, testGcjLon) = wgs84ToGcj02(lat: wgsLat, lon: wgsLon, force: true)
            wgsLat -= (testGcjLat - lat)
            wgsLon -= (testGcjLon - lon)
        }

        return (wgsLat, wgsLon)
    }

    static func gcj02ToWgs84(_ coord: CLLocationCoordinate2D, force: Bool = false) -> CLLocationCoordinate2D {
        let (lat, lon) = gcj02ToWgs84(lat: coord.latitude, lon: coord.longitude, force: force)
        return CLLocationCoordinate2D(latitude: lat, longitude: lon)
    }

    // MARK: GCJ-02 -> BD-09 (百度加密)
    static func gcj02ToBd09(lat: Double, lon: Double) -> (lat: Double, lon: Double) {
        let z = sqrt(lon * lon + lat * lat) + 0.00002 * sin(lat * x_pi)
        let theta = atan2(lat, lon) + 0.000003 * cos(lon * x_pi)
        let bdLon = z * cos(theta) + 0.0065
        let bdLat = z * sin(theta) + 0.006
        return (bdLat, bdLon)
    }

    static func gcj02ToBd09(_ coord: CLLocationCoordinate2D) -> CLLocationCoordinate2D {
        let (lat, lon) = gcj02ToBd09(lat: coord.latitude, lon: coord.longitude)
        return CLLocationCoordinate2D(latitude: lat, longitude: lon)
    }

    // MARK: BD-09 -> GCJ-02 (百度解密)
    static func bd09ToGcj02(lat: Double, lon: Double) -> (lat: Double, lon: Double) {
        let x = lon - 0.0065
        let y = lat - 0.006
        let z = sqrt(x * x + y * y) - 0.00002 * sin(y * x_pi)
        let theta = atan2(y, x) - 0.000003 * cos(x * x_pi)
        let gcjLon = z * cos(theta)
        let gcjLat = z * sin(theta)
        return (gcjLat, gcjLon)
    }

    static func bd09ToGcj02(_ coord: CLLocationCoordinate2D) -> CLLocationCoordinate2D {
        let (lat, lon) = bd09ToGcj02(lat: coord.latitude, lon: coord.longitude)
        return CLLocationCoordinate2D(latitude: lat, longitude: lon)
    }

    // MARK: BD-09 <-> WGS-84
    static func bd09ToWgs84(_ coord: CLLocationCoordinate2D, force: Bool = false) -> CLLocationCoordinate2D {
        let gcj = bd09ToGcj02(coord)
        return gcj02ToWgs84(gcj, force: force)
    }

    static func wgs84ToBd09(_ coord: CLLocationCoordinate2D, force: Bool = false) -> CLLocationCoordinate2D {
        let gcj = wgs84ToGcj02(coord, force: force)
        return gcj02ToBd09(gcj)
    }

    // MARK: 统一归一化为注入 devicectl 所需的标准 WGS-84 坐标
    static func prepareWGS84ForInjection(_ coord: CLLocationCoordinate2D, mode: ChinaCorrectionMode) -> CLLocationCoordinate2D {
        switch mode {
        case .auto:
            if isInChina(coord) {
                return gcj02ToWgs84(coord)
            } else {
                return coord
            }
        case .forcedGCJ02:
            return gcj02ToWgs84(coord, force: true)
        case .forcedBD09:
            return bd09ToWgs84(coord, force: true)
        case .directWGS84:
            return coord
        }
    }

    static func toWGS84(_ coord: CLLocationCoordinate2D, from: CoordinateSystem) -> CLLocationCoordinate2D {
        guard isInChina(coord) else {
            return coord
        }
        switch from {
        case .wgs84:
            return coord
        case .gcj02:
            return gcj02ToWgs84(coord)
        case .bd09:
            return bd09ToWgs84(coord)
        }
    }

    // MARK: 任意坐标系间相互转换
    static func convert(_ coord: CLLocationCoordinate2D, from: CoordinateSystem, to: CoordinateSystem) -> CLLocationCoordinate2D {
        guard isInChina(coord) && from != to else {
            return coord
        }
        // 桥接到 WGS-84
        let wgs = toWGS84(coord, from: from)
        switch to {
        case .wgs84:
            return wgs
        case .gcj02:
            return wgs84ToGcj02(wgs)
        case .bd09:
            return wgs84ToBd09(wgs)
        }
    }

    // MARK: - 内部基础变换数学方程
    private static func transformLat(x: Double, y: Double) -> Double {
        var ret = -100.0 + 2.0 * x + 3.0 * y + 0.2 * y * y + 0.1 * x * y + 0.2 * sqrt(abs(x))
        ret += (20.0 * sin(6.0 * x * .pi) + 20.0 * sin(2.0 * x * .pi)) * 2.0 / 3.0
        ret += (20.0 * sin(y * .pi) + 40.0 * sin(y / 3.0 * .pi)) * 2.0 / 3.0
        ret += (160.0 * sin(y / 12.0 * .pi) + 320.0 * sin(y * .pi / 30.0)) * 2.0 / 3.0
        return ret
    }

    private static func transformLon(x: Double, y: Double) -> Double {
        var ret = 300.0 + x + 2.0 * y + 0.1 * x * x + 0.1 * x * y + 0.1 * sqrt(abs(x))
        ret += (20.0 * sin(6.0 * x * .pi) + 20.0 * sin(2.0 * x * .pi)) * 2.0 / 3.0
        ret += (20.0 * sin(x * .pi) + 40.0 * sin(x / 3.0 * .pi)) * 2.0 / 3.0
        ret += (150.0 * sin(x / 12.0 * .pi) + 300.0 * sin(x / 30.0 * .pi)) * 2.0 / 3.0
        return ret
    }
